#!/usr/bin/env python3
"""Generate rust/src/ui2/tokens.rs from design/figma-tokens.json (exported from Figma)."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent
data = json.loads((root / "figma-tokens.json").read_text())
fields = list(data["color"].keys())


def ident(name: str) -> str:
    return name.replace("/", "_").replace("-", "_")


def color(rgba) -> str:
    r, g, b, a = rgba
    if a == 255:
        return f"Color32::from_rgb({r}, {g}, {b})"
    pm = lambda c: c * a // 255
    return f"Color32::from_rgba_premultiplied({pm(r)}, {pm(g)}, {pm(b)}, {a})"


out = [
    "// @generated by design/gen_tokens.py from design/figma-tokens.json. Do not edit by hand.",
    "use eframe::egui::Color32;",
    "",
    "#[derive(Clone, Copy, Debug, PartialEq)]",
    "pub struct Palette {",
]
out += [f"    pub {ident(f)}: Color32," for f in fields]
out += ["}", ""]
for mode in ("dark", "light"):
    out.append(f"pub const {mode.upper()}: Palette = Palette {{")
    out += [f"    {ident(f)}: {color(data['color'][f][mode])}," for f in fields]
    out += ["};", ""]
out.append("pub mod space {")
names = lambda k: k.upper().replace("2XL", "XXL").replace("3XL", "XXXL")
out += [f"    pub const {names(k)}: f32 = {float(v)};" for k, v in data["space"].items()]
out += ["}", "", "pub mod radius {"]
out += [f"    pub const {k.upper()}: u8 = {v};" for k, v in data["radius"].items()]
out += ["}", ""]
(root.parent / "rust" / "src" / "ui2" / "tokens.rs").write_text("\n".join(out))
print("wrote tokens.rs", len(fields), "colors")
